#!/usr/bin/env node
// Scripted OpenAI-compatible LLM for exercising a real `opencode serve` without network access.
// Each user prompt is turned into a deterministic plan of tool calls (todowrite, write, bash, question)
// which OpenCode executes for real, so the UI sees genuine events, permissions, diffs and todos.
import http from "node:http"

const PORT = Number(process.env.MOCK_LLM_PORT ?? 4555)
const DELAY = Number(process.env.MOCK_LLM_DELAY ?? 25)
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

function textOf(content) {
  if (typeof content === "string") return content
  if (Array.isArray(content)) return content.map((c) => (typeof c === "string" ? c : (c.text ?? ""))).join("")
  return ""
}

function slugify(s) {
  return (
    s
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, "")
      .split("-")
      .slice(0, 4)
      .join("-") || "notes"
  )
}

function workingDir(messages) {
  for (const m of messages) {
    if (m.role !== "system") continue
    const t = textOf(m.content)
    const match = t.match(/Working directory:\s*(\S+)/i) ?? t.match(/<cwd>\s*(\S+)\s*<\/cwd>/i)
    if (match) return match[1]
  }
  return process.cwd()
}

function plan(prompt, cwd) {
  const slug = slugify(prompt)
  const file = `${cwd}/${slug}.md`
  const lower = prompt.toLowerCase()
  const todos = (done) => [
    { content: "Understand the request", status: "completed", priority: "high" },
    { content: `Write ${slug}.md`, status: done ? "completed" : "in_progress", priority: "high" },
    { content: "Verify the result", status: done ? "completed" : "pending", priority: "medium" },
  ]
  const steps = [
    { text: "Let me break this down into steps.", tool: "todowrite", args: { todos: todos(false) } },
    {
      text: `Writing \`${slug}.md\`.`,
      tool: "write",
      args: { filePath: file, content: `# ${prompt}\n\nGenerated by the mock agent.\n\n- step one\n- step two\n` },
    },
  ]
  if (/\b(bash|run|test|verify)\b/.test(lower))
    steps.push({ text: "Running a quick check.", tool: "bash", args: { command: `ls ${cwd}`, description: "List files" } })
  if (/\b(ask|question|choose)\b/.test(lower))
    steps.push({
      text: "I need a decision from you.",
      tool: "question",
      args: {
        questions: [
          {
            question: "Which style should the final summary use?",
            header: "Style",
            options: [
              { label: "Concise", description: "Short bullet points" },
              { label: "Detailed", description: "Full paragraphs" },
            ],
          },
        ],
      },
    })
  steps.push({ text: "Marking everything complete.", tool: "todowrite", args: { todos: todos(true) } })
  return {
    steps,
    final: `Done. I created **${slug}.md** with an outline for:\n\n> ${prompt}\n\n| Step | Status |\n| --- | --- |\n| Plan | ✅ |\n| Write file | ✅ |\n| Verify | ✅ |`,
  }
}

function chunk(id, model, delta, finish = null, usage) {
  const body = {
    id,
    object: "chat.completion.chunk",
    created: Math.floor(Date.now() / 1000),
    model,
    choices: [{ index: 0, delta, finish_reason: finish }],
  }
  if (usage) body.usage = usage
  return `data: ${JSON.stringify(body)}\n\n`
}

async function streamText(res, id, model, text) {
  const words = text.split(/(\s+)/)
  for (const w of words) {
    if (!w) continue
    res.write(chunk(id, model, { content: w }))
    if (DELAY) await sleep(DELAY)
  }
}

async function handle(req, res, body) {
  const model = body.model ?? "scripted"
  const id = `chatcmpl-${Math.random().toString(36).slice(2)}`
  const messages = body.messages ?? []
  const lastUserIdx = messages.findLastIndex((m) => m.role === "user")
  const prompt = textOf(messages[lastUserIdx]?.content).trim()
  const usage = { prompt_tokens: 1200 + prompt.length, completion_tokens: 180, total_tokens: 1380 + prompt.length }

  res.writeHead(200, { "content-type": "text/event-stream", "cache-control": "no-cache", connection: "keep-alive" })
  res.write(chunk(id, model, { role: "assistant", content: "" }))

  // Requests without tools are auxiliary (title generation, summaries).
  if (!body.tools?.length) {
    const title = prompt.replace(/\s+/g, " ").split(" ").slice(0, 6).join(" ")
    await streamText(res, id, model, title || "New task")
    res.write(chunk(id, model, {}, "stop", usage))
    res.end("data: [DONE]\n\n")
    return
  }

  const after = messages.slice(lastUserIdx + 1)
  const stage = after.filter((m) => m.role === "assistant" && m.tool_calls?.length).length
  const { steps, final } = plan(prompt, workingDir(messages))
  const step = steps[stage]
  if (!step) {
    await streamText(res, id, model, final)
    res.write(chunk(id, model, {}, "stop", usage))
    res.end("data: [DONE]\n\n")
    return
  }
  await streamText(res, id, model, step.text)
  res.write(
    chunk(id, model, {
      tool_calls: [
        { index: 0, id: `call_${stage}_${Date.now()}`, type: "function", function: { name: step.tool, arguments: JSON.stringify(step.args) } },
      ],
    }),
  )
  res.write(chunk(id, model, {}, "tool_calls", usage))
  res.end("data: [DONE]\n\n")
}

http
  .createServer((req, res) => {
    if (req.method === "GET" && req.url?.endsWith("/models")) {
      res.writeHead(200, { "content-type": "application/json" })
      return res.end(JSON.stringify({ object: "list", data: [{ id: "scripted", object: "model" }] }))
    }
    if (req.method !== "POST" || !req.url?.includes("/chat/completions")) {
      res.writeHead(404)
      return res.end()
    }
    let raw = ""
    req.on("data", (d) => (raw += d))
    req.on("end", () => {
      let body
      try {
        body = JSON.parse(raw)
      } catch {
        res.writeHead(400)
        return res.end()
      }
      if (process.env.MOCK_LLM_LOG) console.error(JSON.stringify(body.messages?.map((m) => [m.role, textOf(m.content).slice(0, 120)])))
      handle(req, res, body).catch((e) => {
        console.error(e)
        res.end()
      })
    })
  })
  .listen(PORT, "127.0.0.1", () => console.log(`mock-llm listening on http://127.0.0.1:${PORT}/v1`))
